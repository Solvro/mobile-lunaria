const dictionaries: Record<Language, Record<Key, string>> = { en, pl };

export type TranslationKey = Key;

export function translate(language: Language, key: Key, params: Record<string, string | number> = {}) {
  return dictionaries[language][key].replace(/\{(\w+)\}/g, (match, name) => (name in params ? String(params[name]) : match));
}

export function useI18n() {
  const { language } = usePreferences();
  const t = (key: Key, params?: Record<string, string | number>) => translate(language, key, params);
  const locale = language === 'pl' ? 'pl-PL' : 'en-GB';
  const days = (n: number) => t(n === 1 ? 'unit.day.one' : 'unit.day.many', { n });
  return { t, locale, language, days };
}
